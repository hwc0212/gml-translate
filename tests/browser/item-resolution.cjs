const fs=require('fs'),path=require('path');
const {chromium}=require(process.env.GML_PLAYWRIGHT_MODULE||'playwright');
const base=process.env.GML_BROWSER_BASE||'http://127.0.0.1:8393/gml-resolution-test.php';
const out=process.argv[2];fs.mkdirSync(out,{recursive:true});
const assert=(x,s)=>{if(!x)throw Error(s);console.log('PASS '+s);};
(async()=>{
 const browser=await chromium.launch({channel:process.env.GML_BROWSER_CHANNEL||'msedge',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 await context.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  const setup=await (await context.request.get(base+'?setup=1')).json();assert(setup.success,'isolated browser setup');
  const ordinary=setup.data.text,critical=setup.data.seo_title;
  const url=(item,scope='current',locale='en_US')=>base+'?resource='+item.resource+'&language=de&scope='+scope+'&locale='+locale;
  await page.goto(url(ordinary));
  const nonce=await page.evaluate(()=>gmlPageWorkflow.nonce);
  let response=await context.request.post(url(ordinary),{form:{operation:'keep_source',id:ordinary.id,resource_id:ordinary.resource,nonce:'wrong'}});
  assert(response.status()===403,'invalid nonce blocked');
  response=await context.request.post(base+'?anonymous=1',{form:{operation:'keep_source',id:ordinary.id,nonce}});
  assert(response.status()===403,'anonymous write blocked');
  const keep=page.locator('form').filter({has:page.locator('input[value="keep_source"]')});
  const fields=await keep.evaluate(f=>Object.fromEntries(new FormData(f)));fields.nonce=nonce;
  await Promise.all([page.waitForNavigation(),keep.locator('button').click()]);
  assert(await page.locator('[data-queue-id="'+ordinary.id+'"]').count()===0,'resolved item leaves current attention');
  response=await context.request.post(url(ordinary),{form:fields});
  assert(response.status()===409,'old browser snapshot rejected');
  await page.goto(url(ordinary,'resolved'));
  assert(await page.getByRole('button',{name:'Revoke Keep source',exact:true}).count()===1,'exact page decision revocable');
  await page.screenshot({path:path.join(out,'desktop-kept-source.png'),fullPage:true});
  await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Revoke Keep source',exact:true}).click()]);
  await page.goto(url(ordinary));
  await page.locator('textarea[name="translation"]').fill('Technische Abmessungen 90*45*30mm');
  await Promise.all([page.waitForNavigation(),page.getByRole('button',{name:'Save Manual Translation',exact:true}).click()]);
  assert(await page.locator('[data-queue-id="'+ordinary.id+'"]').count()===0,'manual save refreshes current list');
  await page.goto(url(critical));
  const criticalForm=page.locator('form').filter({has:page.locator('input[value="keep_source"]')});
  assert(await criticalForm.locator('[name="critical_confirmation"]').getAttribute('required')!==null,'critical confirmation required in UI');
  const criticalFields=await criticalForm.evaluate(f=>Object.fromEntries(new FormData(f)));
  criticalFields.nonce=await page.evaluate(()=>gmlPageWorkflow.nonce);
  response=await context.request.post(url(critical),{form:criticalFields});
  assert(response.status()===409,'critical confirmation also enforced server-side');
  await criticalForm.locator('[name="critical_confirmation"]').check();
  await Promise.all([page.waitForNavigation(),criticalForm.locator('button').click()]);
  await page.setViewportSize({width:390,height:844});
  await page.goto(url(critical,'resolved','zh_CN'));
  assert(await page.getByRole('button',{name:'撤销使用原文',exact:true}).count()===1,'Chinese keep-source action translated');
  const geometry=await page.getByRole('button',{name:'撤销使用原文',exact:true}).evaluate(el=>{const r=el.getBoundingClientRect();return {right:r.right,left:r.left,overflow:document.documentElement.scrollWidth>innerWidth};});
  assert(geometry.left>=0 && geometry.right<=390 && !geometry.overflow,'mobile action visible without horizontal scrolling');
  await page.screenshot({path:path.join(out,'mobile-zh-kept-source.png'),fullPage:true});
  await page.goto(base+'?tab=pages&locale=zh_CN');
  assert((await page.locator('body').innerText()).includes('已解决覆盖率'),'Chinese dual coverage rendered');
  await page.screenshot({path:path.join(out,'mobile-zh-progress.png'),fullPage:true});
  const state=await(await context.request.get(base+'?state=1')).json();
  assert(state.data.paused===true||state.data.paused==='1','global queue remains paused');
  assert(state.data.items.text.tm.status==='manual','manual save uses protected TM state');
  assert(!state.data.items.seo_title.tm && state.data.items.seo_title.decision.critical_confirmed==='1','source decision not saved as translation');
  assert(errors.length===0,'no browser JavaScript errors');
  fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({result:'PASS',errors,viewportWidths:[1440,390],productionRequests:0},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
